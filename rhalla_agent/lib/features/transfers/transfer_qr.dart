/* ══════════════════════════════════════════════════════════════════════════
   رمزُ استلام الحوالة — نصّاً ورمزَ QR
   ══════════════════════════════════════════════════════════════════════════

   ⚠ **ما يحمله هذا الرمز هو بعينه ما هو مطبوعٌ بجانبه — ولا شيءَ سواه.**

   رمزُ QR على مستندٍ ماليّ يُغري بالظنّ أنه مفتاحٌ يُسلّم المال. وهو هنا
   **ليس كذلك**: مجرّدُ نسخةٍ آليّةٍ من الأرقام المكتوبة تحته، غايتُها ألّا
   يُملي الزبونُ رقماً ولا يخطئ الوكيل في نسخه.

   والتسليمُ بعده يمرّ بما يمرّ به دائماً: جلسةُ الوكيل، وصلاحيةُ التسليم،
   والتحوُّلُ الذرّيّ الذي يمنع التسليم مرّتين. فمن صوّر الرمز لم يملك شيئاً
   لم يكن يملكه بقراءة الأرقام بعينه.

   ── ولماذا بادئة ─────────────────────────────────────────────────────────

   لتمييزه عن **رمز تفعيل الموظف** (٦٤ خانة ستّ عشريّة) قبل الشبكة: ماسحٌ
   يقبل كلَّ شيء يجعل رمزَ تفعيلٍ مصوَّراً يُبحث به عن حوالة، فتظهر «لا نتيجة»
   ولا يفهم الوكيل لماذا.

   ── ⚠ ومع ذلك يُقبل الرقمُ المجرَّد ────────────────────────────────────────

   إيصالٌ من نظامٍ آخر — أو من التطبيق المكتبيّ — قد يحمل رمزاً بلا بادئتنا.
   ورفضُه يعني ماسحاً يعمل مع إيصالاتنا وحدَها، وذلك أسوأ من لا ماسح: الوكيل
   يجرّب فيفشل، فيكفّ عن استعماله حتى مع إيصالاتنا.
   ══════════════════════════════════════════════════════════════════════════ */

/// بادئةُ رموزنا. قصيرةٌ عمداً: كلُّ حرفٍ يزيد كثافةَ الرمز فيصعب مسحُه من
/// ورقةٍ مطبوعةٍ بحبرٍ باهت.
const _prefix = 'RH-T:';

/// شكلُ رقم الحوالة كما يُصدره النظام — أرقامٌ وشُرَط (`13151-54-1`).
///
/// ⚠ ويقبل الحروفَ أيضاً: رموزُ الموبايل في بعض الفروع تحمل حروفاً، ورفضُها
/// يجعل الماسحَ يصمت أمام إيصالٍ صحيح.
final _codeShape = RegExp(r'^[A-Za-z0-9][A-Za-z0-9\-]{2,39}$');

/// رمزُ تفعيل الموظف — ٦٤ خانةً ستّ عشريّة. يُرفض هنا صراحةً.
final _activationShape = RegExp(r'^[0-9a-f]{64}$');

/// ما يُكتب داخل رمز QR على الإيصال.
String transferQrPayload(String code) => '$_prefix${code.trim()}';

/// يقرأ رمزاً ممسوحاً ويُعيد رقمَ الحوالة، أو `null` إن لم يكن رمزَ حوالة.
///
/// ⚠ **الفحصُ قبل الشبكة لا بعدها.** الكاميرا في مكتب صرافةٍ ترى رموزَ
/// فواتيرَ وشبكاتِ واي فاي وملصقاتِ منتجات؛ وإرسالُ أيٍّ منها بحثاً يُعيد
/// «لا نتيجة» — فيظنّ الوكيل أن إيصال الزبون هو المعطوب.
String? readTransferQr(String raw) {
  var s = raw.trim();
  if (s.isEmpty) return null;

  final hasPrefix = s.toUpperCase().startsWith(_prefix);
  if (hasPrefix) s = s.substring(_prefix.length).trim();

  if (s.isEmpty) return null;

  /*
   * ⚠ رمزُ تفعيل الموظف يُرفض **ولو حمل بادئتنا**.
   *
   * لا لأنه خطرٌ — البحثُ به لا يفعل شيئاً — بل لأنّ نتيجتَه «لا حوالة بهذا
   * الرقم»، وهي جملةٌ تُرسل الوكيل يبحث عن عطبٍ في مكانٍ سليم.
   */
  if (_activationShape.hasMatch(s.toLowerCase())) return null;

  if (!_codeShape.hasMatch(s)) return null;

  /*
   * ⚠ وبلا بادئةٍ يُشترط رقمٌ فيه شُرطة أو طولٌ معقول.
   *
   * رمزُ QR على علبة عصيرٍ قد يكون `12345`، ومسحُه سهواً يفتح بحثاً عن حوالةٍ
   * لا وجودَ لها. أمّا ما حمل بادئتَنا فهو رمزُنا يقيناً، فيُقبل كما هو.
   */
  if (!hasPrefix && !s.contains('-') && s.length < 6) return null;

  return s;
}
