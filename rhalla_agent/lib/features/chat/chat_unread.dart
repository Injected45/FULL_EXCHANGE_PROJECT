import 'dart:async';

import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'chat_repository.dart';

/// عدّاد الرسائل غير المقروءة — للشارة في شريط التبويبات.
///
/// منفصلٌ عن [chatThreadsProvider] عمداً: تلك تجلب الأسماء وآخرَ رسالةٍ لكل
/// محادثة، وسحبُها من أجل رقمٍ واحد إهدارٌ لشبكة الوكيل. وهذه نقطةٌ تعيد
/// عدداً.
///
/// ── التنبيه: اهتزازةٌ لا رنّة (أمر المالك، 6 سبتمبر 2026) ────────────────
///
/// كان هذا العدّاد **صامتاً تماماً** بقرارٍ سابق: «الحوالة الواردة عملٌ
/// ينتظر ومالٌ يُدفع، والرسالة كلام؛ وصوتان يتنازعان انتباه الوكيل يجعلانه
/// يتجاهلهما معاً».
///
/// وكانت نتيجتُه أن رسالةً من الإدارة تصل والوكيل على الشاشة الرئيسية فلا
/// يعلم بها إطلاقاً — لا صوتَ ولا اهتزاز، ورقمٌ صغير في شريطٍ أسفل الشاشة
/// قد لا ينظر إليه. فبدا الأمر «الرسالة لم تصل» لا «وصلت ولم أُنبَّه».
///
/// والحلّ يحفظ المنطق الأصلي: **اهتزازةٌ خفيفة بلا صوت**. فالجرسُ يبقى
/// وحده صاحبَ الصوت — لا يتنازعه شيء — وتنال الرسالةُ إشارةً يشعر بها
/// صاحبُ الهاتف في يده ولا تُنازع أذنَه.
///
/// وثلاثةُ شروطٍ للاهتزاز، وكلُّها مقصودة:
///   1. **لا اهتزاز في أوّل قراءة** — تُثبّت الأساس. ورسائلُ كانت قبل فتح
///      التطبيق يعلنها الرقم صامتاً، وإلا اهتزّ الهاتف عند كل فتحة.
///   2. **عند الزيادة وحدها** — النزول يعني أنه قرأها، والثبات لا جديد فيه.
///   3. **لا اهتزاز حين تكون المحادثة مفتوحة أمامه** — شاشة المحادثة تُعلّم
///      المقروء فينزل العدّاد، فلا يزيد أصلاً.
class ChatUnreadController extends StateNotifier<int> {
  ChatUnreadController(this._repo) : super(0);

  final ChatRepository _repo;

  /// ‏`null` تعني «لم تُقرأ بعد» — بها يُعرف أوّل نداء.
  int? _lastKnown;

  /// وضع الموظّف يسأل نقطةً أخرى — محادثته هو وحدها.
  bool employeeMode = false;

  Timer? _timer;
  bool _busy = false;

  /// ثماني ثوانٍ لا ثلاثون.
  ///
  /// ⚠ هذه النقطة هي **كيف يعرف الوكيل أن رسالةً وصلته وهو خارج شاشة
  /// المحادثة** — على الشاشة الرئيسية أو التقارير أو الحساب. وثلاثون ثانية
  /// كانت تعني أن رسالةً من الإدارة قد تنتظر نصف دقيقةٍ قبل أن تظهر شارتُها،
  /// وهو ما يبدو للمستخدم «لم تصل» لا «تأخّرت».
  ///
  /// وصار ذلك ممكناً لأن النداء رخص: **استعلامٌ واحد بدل ثلاثة**. ولا يعمل
  /// إلا والتطبيق أمام المستخدم — `AutoRefresh` توقفه عند التصغير، فلا
  /// أثر على البطارية في الخلفية.
  static const every = Duration(seconds: 8);

  void start() {
    _timer?.cancel();
    _timer = Timer.periodic(every, (_) => refresh());
    refresh();
  }

  void stop() {
    _timer?.cancel();
    _timer = null;
  }

  void reset() {
    stop();
    state = 0;
    // الأساس يُنسى مع الخروج: الداخل بعده يبدأ من جديد، ولو بقي لاهتزّ
    // الهاتف لتاريخِ محادثاتٍ كاملٍ عند أوّل دخول.
    _lastKnown = null;
  }

  Future<void> refresh() async {
    if (_busy) return;
    _busy = true;
    try {
      final n = employeeMode
          ? await _repo.employeeUnread()
          : await _repo.unread();

      // ‏-1 تعني «تعذّرت القراءة» لا «صفر»: الشارة تبقى على آخر ما تعرف بدل
      // أن تختفي مع أول انقطاع فيظنّ الوكيل أنه قرأ كل شيء.
      if (n < 0) return;

      final before = _lastKnown;
      _lastKnown = n;
      if (n != state) state = n;

      // الشروط الثلاثة — انظر ترويسة الصنف.
      if (before != null && n > before) _buzz();
    } finally {
      _busy = false;
    }
  }

  /// اهتزازةٌ بلا صوت.
  ///
  /// `HapticFeedback` مبنيّ في Flutter — لا حزمة ولا ملفّ صوتٍ في الـ APK.
  /// ويعمل والهاتف صامت، وهو المطلوب: الوكيل قد يكون في فرعٍ صاخب أو في
  /// اجتماع، والاهتزاز يصله في الحالين.
  Future<void> _buzz() async {
    try {
      await HapticFeedback.mediumImpact();
    } catch (_) {
      // جهازٌ بلا هزّاز — الشارة تبقى، ولا شيء يُكسر.
    }
  }

  @override
  void dispose() {
    _timer?.cancel();
    super.dispose();
  }
}

final chatUnreadProvider =
    StateNotifierProvider<ChatUnreadController, int>(
  (ref) => ChatUnreadController(ref.watch(chatRepositoryProvider)),
);
