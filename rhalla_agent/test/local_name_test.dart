import 'package:flutter_test/flutter_test.dart';
import 'package:rhalla_agent/core/format/fmt.dart';

/// أسماء الحركات تأتي من `OperationTypeTb` في قاعدة بيانات مشتركة مع تطبيق
/// سطح المكتب، فلا تُغيَّر هناك — تُترجَم عند العرض. وهذه الاختبارات تثبّت
/// الترجمة، وأهمّها الأخير: ما ليس حوالةً لا يُمسّ.
void main() {
  group('Fmt.localName', () {
    test('«حوالة داخلية» تصير «حوالة محلية»', () {
      expect(Fmt.localName('حوالة داخلية'), 'حوالة محلية');
      expect(Fmt.localName('حوالة داخلية صادرة'), 'حوالة محلية صادرة');
      expect(Fmt.localName('حوالة داخلية واردة ملغية'), 'حوالة محلية واردة ملغية');
    });

    test('الجمع والصفة المعرّفة كذلك', () {
      expect(Fmt.localName('حوالات داخلية ملغاة'), 'حوالات محلية ملغاة');
      expect(Fmt.localName('إيرادات حوالات واردة داخلية'),
          'إيرادات حوالات واردة محلية');
      expect(Fmt.localName('عمولة داخلية للرئيسي بين الفروع'),
          'عمولة محلية للرئيسي بين الفروع');
    });

    test('«ال» التعريف تبقى: «الداخلية» ⇦ «المحلية»', () {
      expect(Fmt.localName('الحوالات الداخلية'), 'الحوالات المحلية');
    });

    test('المذكّر لا يُمسّ — «نقل داخلي مع تاكسي» ليس حوالة', () {
      expect(Fmt.localName('ارسال فاتورة نقل داخلي مع تاكسي'),
          'ارسال فاتورة نقل داخلي مع تاكسي');
    });

    test('ما لا يحوي الكلمة يمرّ كما هو، والفارغ يبقى فارغاً', () {
      expect(Fmt.localName('حوالة خارجية صادرة'), 'حوالة خارجية صادرة');
      expect(Fmt.localName(''), '');
      expect(Fmt.localName(null), '');
    });
  });
}
