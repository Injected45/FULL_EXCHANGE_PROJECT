import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

/**
 * يُبنى إلى `backend/public/support/` ويُقدَّم من Laravel نفسِه.
 *
 * ── لماذا نفس الخادم لا استضافةٌ ثانية ──────────────────────────────────
 *
 * نفسُ الأصل (origin) يعني: لا CORS، ولا شهادةَ ثانية، ولا نطاقاً يُشترى،
 * ولا خادماً يُدفع ثمنُه شهرياً — وأمرُ المالك صريح: «كل ما يحتاج اشتراكاً
 * شهرياً ومصاريفَ لا داعي له». وهو أيضاً أبسط في التشغيل: نسخةٌ واحدة
 * تُرفع، وعنوانٌ واحد يُحفظ.
 *
 * ── ⚠ `base` مطلقٌ لا نسبيّ — وهذا خطأٌ كلّف صفحةً لا تعمل ────────────────
 *
 * كان `'./'`، والحجّة أن المسار النسبيّ «ينتقل معك». والنتيجة أن الصفحة
 * **لم تُركَّب في أي متصفّح**: Laravel يقدّمها على `/support` **بلا شرطة
 * مائلة**، فيحلّ المتصفّح `./assets/index.js` إلى `/assets/index.js` —
 * أي جذرَ الموقع — فيعود 404 ولا يعمل React، والصفحة تبقى بيضاء بلا رسالة
 * خطأ واحدة.
 *
 * ولم يكشفه اختبارٌ سابق لأنه جلب الأصل بيده بالمسار الصحيح بدل أن يحلّه
 * كما يفعل المتصفّح — فمرّ الاختبار والصفحة معطّلة. الكشفُ جاء من تصييرٍ
 * حقيقيّ في متصفّحٍ بلا واجهة.
 *
 * والمطلق `/support/` يعمل من `/support` ومن `/support/` معاً. وإن نُقلت
 * الصفحة يوماً إلى مسارٍ آخر، فهذا السطر هو ما يُغيَّر — سطرٌ واحدٌ معلومٌ
 * خيرٌ من عطبٍ صامت.
 */
export default defineConfig({
  plugins: [react()],
  base: '/support/',
  // ⚠ ضروريّ: Vite يصعد بحثاً عن `postcss.config.js` فيجد ملفّ Laravel في
  // `backend/` — وفيه Tailwind غير المثبَّت هنا، فيفشل البناء برسالةٍ عن
  // «وحدة مفقودة» لا علاقة لها بهذا المشروع. تنسيقُنا CSS خالص بمتغيّراتٍ
  // أصلية، فالحلُّ أن يُقال له صراحةً: لا PostCSS.
  css: { postcss: {} },
  build: {
    outDir: '../public/support',
    emptyOutDir: true,
    // أصولٌ بأسماءٍ مبصومة، فتُخزَّن في المتصفّح طويلاً بلا خوفِ قِدَم.
    assetsDir: 'assets',
    // خريطةُ المصدر مطفأة في الإصدار: تكشف الكود لمن يفتح الأدوات، وتضاعف
    // ما يُرفع، ولا تفيد أحداً على خادم الشركة.
    sourcemap: false,

    /*
     * ⚠ هدفٌ صريح — لا افتراضُ Vite الحديث.
     *
     * Vite يستهدف افتراضياً ما هو «متاحٌ على نطاق واسع»، فيُخرج شيفرةً
     * تعتمد دوالَّ حديثة (`Array.at`, `Object.hasOwn`, `structuredClone`…).
     * وهاتفٌ يحمل System WebView قديماً يفتح الصفحة **بيضاء تماماً بلا
     * رسالة خطأ** — لا تحميلَ فاشلاً ولا تحذيراً، فقط لا شيء.
     *
     * ومحاكي API 30 يحمل WebView 83 (2020)، وهواتفُ ليبيا فيها ما هو أقدم.
     * `es2017` يشمل `async/await` و`Object.entries` — وهو كلُّ ما تحتاجه
     * هذه اللوحة — ويعمل على WebView 60 فما فوق.
     *
     * والثمن بضعةُ كيلوبايتات في الحزمة، مقابل صفحةٍ تعمل على كل هاتف.
     */
    target: 'es2017',
  },
  server: {
    port: 5174,
    proxy: {
      // في التطوير وحده: `npm run dev` على 5174 و Laravel على 8000.
      '/api': { target: 'http://127.0.0.1:8000', changeOrigin: true },
    },
  },
})
