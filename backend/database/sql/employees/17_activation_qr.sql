/* ============================================================================
   تفعيل الموظف بواسطة QR — أعمدةٌ على الصفّ القائم لا جدولٌ ثانٍ
   ============================================================================

   ⚠ **QR ليس طلبَ تفعيلٍ آخر، بل تمثيلٌ ثانٍ للطلب نفسِه.**

   ولذلك لا جدولَ جديداً: الأعمدةُ تُضاف إلى `employee_activation_codes`،
   فيرث الرمزُ دورةَ حياة الكود كلَّها بلا سطرِ منطقٍ مكرَّر —

     • الحالةُ واحدة    (ACTIVE · USED · REVOKED · EXPIRED · COMPROMISED)
     • والمدّةُ واحدة   (`expires_at` — عشر دقائق)
     • والإلغاءُ واحد   (إصدارُ رمزٍ جديد يُبطل السابق)
     • والاستهلاكُ واحد (يصير USED عند نجاح التفعيل)

   وجدولٌ موازٍ كان سيعني حالتين لطلبٍ واحد تفترقان عند أوّل تعديل: كودٌ
   مُلغى ورمزٌ ما زال يعمل.

   ── ثلاثة قرارات ─────────────────────────────────────────────────────────

   1. **يُخزَّن مُجزَّأً (SHA-256) لا نصّاً.** الرمزُ مفتاحُ تفعيل، ومن قرأ
      الجدول لا ينبغي أن يستطيع تفعيل جهاز. وهو مبدأ `code_hash` نفسُه.

   2. **`scan_device_hash` يحسم التزامن.** أوّلُ جهازٍ يمسح يُثبَّت في هذا
      العمود بتحديثٍ شرطيّ، فمن جاء بعده يُرفض — وهو ما يمنع «جهازين
      يمسحان الرمز نفسَه في اللحظة نفسِها». والحارسُ القاعدةُ لا الشيفرة:
      طلبان متوازيان يمرّان معاً على أي فحصٍ في الذاكرة.

   3. **الفهرسُ فريدٌ على المُجزَّأ** — فلا رمزان متطابقان، ولا يُقرأ الجدول
      كلُّه عند كل مسح.

   ⚠ ولا شيء هنا يمسّ المال: أعمدةُ تفعيلِ جهاز.

   قابل لإعادة التنفيذ: محروسٌ بـ IF، ولا DROP ولا حذف بيانات.
   ============================================================================ */

SET ANSI_NULLS ON;
GO
SET QUOTED_IDENTIFIER ON;
GO

IF COL_LENGTH('dbo.employee_activation_codes', 'qr_token_hash') IS NULL
BEGIN
    ALTER TABLE dbo.employee_activation_codes ADD
        /* SHA-256 للرمز العشوائي — 64 محرفاً ستّ عشريّاً. */
        qr_token_hash    VARCHAR(64)  NULL,
        qr_issued_at     DATETIME2    NULL,

        /* أوّلُ جهازٍ مسح الرمز — يحسم التزامن قبل إرسال أي رمز تحقّق. */
        scanned_at       DATETIME2    NULL,
        scan_device_hash VARCHAR(64)  NULL;
END;
GO

/*
   فريدٌ ومُرشَّح: الفهرسُ الفريد على عمودٍ يقبل NULL يمنع تكرار المُجزَّأ،
   والترشيحُ يستثني الصفوفَ التي لا رمزَ لها — وهي كلُّ الأكواد القديمة.

   ⚠ ويحتاج QUOTED_IDENTIFIER = ON — والسكربت يضبطها بنفسه في أوّله، لأن
   sqlcmd يبدأ بها OFF فيُخفق إنشاء الفهرس المُرشَّح، ولا يُخفق ما قبله:
   فتُضاف الأعمدة ويبقى الجدول بلا فهرسٍ فريد — نصفُ نشرٍ لا يُرى.
*/
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_emp_code_qr'
               AND object_id = OBJECT_ID('dbo.employee_activation_codes'))
    CREATE UNIQUE INDEX UX_emp_code_qr
        ON dbo.employee_activation_codes (qr_token_hash)
        WHERE qr_token_hash IS NOT NULL;
GO
