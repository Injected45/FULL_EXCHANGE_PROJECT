/* ============================================================================
   قناةُ الحوالة في سجلّ النسبة — محلّيةٌ أم خارجية (10 سبتمبر 2026)
   ============================================================================

   أمرُ إعادة هيكلة واجهة تطبيق الموظف فتح له بابَ الحوالة الخارجية طبقَ باب
   الوكيل، وجعل تحتها «حوالاتي» و«كشف الحوالات» — منفصلتين عن المحلّية.

   وللفصل بينهما يلزم أن يقول السجلُّ أيَّ قناةٍ سلكت الحوالة. وبدونه لا
   سبيل إلى ذلك إلّا بأن يُسأل الدفترُ عن كلّ رقمٍ على حدة: هل هو في
   InternalEx أم في ExternalEx؟ — وهو بالضبط الشكلُ الذي جعل كشفَ الحساب
   يستغرق 68 ثانية (‏InternalEx.Code بلا فهرس).

   ⚠ **ولا يمسّ هذا مالاً ولا محاسبة.** `transfer_attributions` جدولٌ
   تشغيليّ **بجوار** الدفتر لا داخله: يقول «من حرّك يده»، ولا يحمل رصيداً
   ولا قيداً ولا عمولة. وقد أُضيف إليه من قبلُ `recipient_phone` و
   `recipient_name_norm` بالقاعدة نفسِها.

   ⚠ والعمودُ **NULL-able بلا قيمةٍ افتراضية تُكتب رجعياً**: كلُّ صفٍّ كُتب
   قبل اليوم حوالةٌ محلّية بالضرورة — لم يكن للموظف بابٌ خارجيّ أصلاً — لكنّ
   تعبئتَه بـ'LOCAL' كتابةٌ على سجلٍّ قائم. فالقراءةُ تعامل NULL معاملةَ
   'LOCAL'، والصفُّ يبقى كما كُتب.

   إضافيٌّ و idempotent.
   ============================================================================ */

IF NOT EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID('dbo.transfer_attributions') AND name = 'channel'
)
    ALTER TABLE dbo.transfer_attributions ADD channel NVARCHAR(16) NULL;
GO

/* فهرسٌ للقراءة التي أُضيف العمودُ من أجلها: حوالاتُ موظفٍ في قناةٍ بعينها.
   ⚠ على جدولٍ تشغيليّ — لا على جدولٍ ماليّ، فالأمرُ الدائم لا يُخالَف. */
IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'IX_attr_employee_channel'
      AND object_id = OBJECT_ID('dbo.transfer_attributions')
)
    CREATE INDEX IX_attr_employee_channel
        ON dbo.transfer_attributions (employee_id, channel, occurred_at DESC);
GO
