     * الخادمُ هو من يحرس كلَّ تقرير.
     *
     * تُعلَن هنا ليعرف `employee_permissions_wiring_check` أنّ غيابَ المسار
     * مقصودٌ لا سهو. وفحصٌ يفشل دائماً يُعلَّم تجاهلُه، فيضيع فشلُه الحقيقيّ.
     */
