    /**
     * ما يراه الوكيل قبل أن يمنح — سببُ الحساسية بعينه، لا تحذيرٌ عامّ.
     *
     * «تحذير» مجرَّدٌ يُقرأ روتيناً، وجملةٌ تقول ماذا سيرى الموظف بالضبط
     * تُقرأ قراراً.
     */
