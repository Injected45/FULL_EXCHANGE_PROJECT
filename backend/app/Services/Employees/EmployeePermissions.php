     *
     * فالصلاحيةُ هنا لا تُغيَّر ولا تُلغى — يُمنع **منحُها ضمناً**. تُختار
     * بيدها، ويُسأل الوكيل قبل تشغيلها.
     *
     * ── ولماذا في الخادم لا في التطبيق ────────────────────────────────────
     *
