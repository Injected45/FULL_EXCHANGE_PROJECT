        'REPORTS_VIEW',
    ];

    /**
     * ما يبقى مفتوحاً للموظف **وهو مُوقَف** ببوّابة الإيقاف.
     *
     * ⚠ شاشةُ التجميد تقول له «تواصل مع الإدارة»، والدردشةُ خلف
     * `CHAT_WITH_AGENT` — فبغير هذا الاستثناء يكون التطبيق قد أمره بفعلٍ
     * يمنعه هو نفسُه: يفتح المراسلة فيُردّ 403 بنفس رسالة الإيقاف، ولا سبيل
     * له إلى وكيله من داخل التطبيق أصلاً.
     *
     * ولا يُوسَّع هذا المصفوف إلّا لما هو **قناةُ تواصل**: كلُّ ما عداه عملٌ،
     * والإيقافُ إنّما وُجد ليمنع العمل. ولا شيءَ هنا يمسّ مالاً — الدردشةُ
     * رسائل، لا رصيدَ ولا قيدَ ولا عمولة.
     */
    public const ALLOWED_WHILE_PAUSED = [
        'CHAT_WITH_AGENT',
    ];

    /** هل يُسمح بهذا المفتاح رغم إيقاف الموظف؟ */
    public static function allowedWhilePaused(string $key): bool
    {
        return in_array($key, self::ALLOWED_WHILE_PAUSED, true);
    }

    /** هل هو مفتاحُ بوّابةِ واجهة لا يفرضه مسار؟ */
    public static function isUiOnly(string $key): bool
    {
        return in_array($key, self::UI_ONLY, true);
    }

    /** هل يُمنع منحُ هذا المفتاح ضمناً مع مجموعته؟ */
    public static function isSensitive(string $key): bool
    {
        return in_array($key, self::SENSITIVE, true);
    }

    /** هل للمفتاح أثرٌ فعليّ اليوم؟ */
    public static function isLive(string $key): bool
    {
        return in_array($key, self::LIVE, true);
    }
    public static function exists(string $key): bool
    {
        return array_key_exists($key, self::CATALOG);
    }

    /** هل يجوز منح هذا المفتاح لموظف أصلاً؟ */
    public static function grantable(string $key): bool
    {
        return self::exists($key)
            && !in_array($key, self::NEVER_FOR_EMPLOYEES, true);
    }

    /** الكتالوج مسطّحاً لشاشة المنح. */
    public static function catalogForAdmin(): array
    {
        $out = [];
        foreach (self::GROUPS as $groupKey => $groupName) {
            $items = [];
            foreach (self::CATALOG as $key => [$g, $label]) {
                if ($g === $groupKey) {
                    $items[] = [
                        'key'   => $key,
                        'label' => $label,
                        // ⚠ الشاشةُ تعرض هذا: مفتاحٌ غير موصولٍ يُمنح
                        // ولا يفعل شيئاً، فيجب أن يقول ذلك بنفسه.
                        'live'  => self::isLive($key),

                        /*
                         * ⚠ «لا يُمنح مع المجموعة» — يُختار بيده وحدَه.
                         *
                         * يُرسَل من الخادم لا يُستنبَط من الاسم: القاعدةُ
                         * أنّ لا مفتاحَ صلاحيةٍ يُكتب في ملفّ Dart، فوسمُ
                         * مفتاحٍ جديد غداً يسري بلا إصدار.
                         */
                        'sensitive' => self::isSensitive($key),
                        'why'       => self::SENSITIVE_WHY[$key] ?? null,
                    ];
                }
            }
            if ($items !== []) {
                $out[] = ['group' => $groupKey, 'name' => $groupName, 'items' => $items];
            }
        }
        return $out;
    }
}
