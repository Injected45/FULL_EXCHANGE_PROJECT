        'VIEW_AGENT_TOTAL_BALANCE' => 'سيرى الموظف رصيد وكالتك الكلّي.',
        'REPORT_AGENT_BALANCE'     => 'سيرى الموظف رصيد وكالتك في التقارير.',
    ];

    /**
