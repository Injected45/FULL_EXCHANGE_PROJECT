<?php

namespace App\Services;

use Illuminate\Support\Facades\DB;

/**
 * حارسُ تسعيرِ الحوالة الخارجية — **سعرٌ واحد، وقراءةٌ واحدة، ومنعُ الخسارة**.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  أمرُ المالك (11 سبتمبر 2026)
 * ══════════════════════════════════════════════════════════════════════════
 *
 * «ننشئ شرطاً وحارساً يمنع أيَّ حوالةٍ بالسالب. حتى لو أخطأ الموظفُ في
 *  المنظومة الخلفية في إدراج الأسعار، ورأيتَ أنّ الحوالة لو نُفِّذت تسبّب
 *  خسارةً للشركة — يوقف الحارسُ الخدمةَ بأدبٍ ويُظهر: «نأسف لعدم اتمام
 *  التحويل . الاسعار في طور التحديث عليك مراجعة الشركة». وإذا كان فرقُ
 *  الأسعار في صالح الشركة والربح + يُنفَّذ التحويل دون أيّ مشاكل.
 *
 *  وما سيتمّ إصلاحه الآن يجري على الحوالات الجديدة، **ولا مساسَ بأيّ حوالةٍ
 *  نُفِّذت حتى وإن كانت بالسالب**».
 *
 * ── ما يحرسه، بعبارةِ محاسب ─────────────────────────────────────────────
 *
 *   CurrDeliveredVal = المبلغ المقبوض بالدينار × سعرِ البيع
 *                      — قيمةُ ما قبضناه، مقوَّمةً بعملة الوجهة.
 *   NetTotal         = ما يُسلَّم للمستفيد فعلاً بعملة الوجهة.
 *   ServiceExVal     = الأولى − الثانية = **هامشُ الشركة**.
 *
 * فسالبُه يعني حرفياً: سلّمنا بعملة الوجهة أكثرَ ممّا يساويه ما قبضناه
 * بالدينار على سعرِ بيعنا نحن. وهي خسارةٌ محقّقةٌ لحظةَ التنفيذ، لا مخاطرةٌ
 * محتملة.
 *
 * ── ولماذا كانت تقع أصلاً ───────────────────────────────────────────────
 *
 * ⚠ الطرفان كانا يُحسبان **بسعرين مختلفين**:
 *
 *   `NetTotal` ← `dbo.SalePrice_mo_Value`، واستعلامُها فيه `b.BankID = @Type_ID_int`
 *   `TransPrice` ← نسخةُ الاستعلام داخل المحفّز، و**ينقصها هذا السطر**
 *
 * فخمسةُ صفوفٍ تتأهّل لمصر، و`SELECT @SalePrice = …` على مجموعةٍ متعدّدة
 * تُبقي آخرَ صفٍّ يصله المنفّذ — سعراً اعتباطياً لا سعرَ الخدمة. ومقيسٌ على
 * القاعدة: تسعُ حوالاتٍ من عشرٍ كُتبت بـ٥٫٣٠٠ وسعرُ خدمتها المُدرج ٥٫٥٥٠،
 * وكلُّ واحدةٍ خرجت بهامشٍ سالب.
 *
 * ── وبعد توحيد السعر، الحارسُ شبكةُ أمانٍ لا عائق ───────────────────────
 *
 * ⚠ حين يُحسب الطرفان بالسعر نفسِه يصير الهامشُ **هو جدولَ الحسم**
 * (`CATEGORYTYPESDETAILSTB`) لا فرقاً بين سعرين — فلا يكون سالباً بنيوياً.
 *
 * وقيسَ ذلك: تسعُ خدماتٍ × اثنا عشر مبلغاً (من 1 إلى 10,000 د.ل) — **أدنى
 * هامشٍ صفر، ولا سالبَ واحد**. فالحارسُ لا يعترض عملاً سليماً؛ لا يتكلّم إلّا
 * حين يُخطئ المكتبُ الخلفيّ في إدراج سعر.
 *
 * ── ⚠ وهامشُ التسامح ليس تجميلاً ────────────────────────────────────────
 *
 * السودان: السعر 555.555 والمبالغ تُضرب فيه، فيخرج الهامشُ من حساب الفاصلة
 * العائمة **−2.9e-13** — صفرٌ رياضياً، سالبٌ في المقارنة الحرفية. وبلا
 * [EPSILON] كانت كلُّ حوالةٍ إلى السودان تُمنع بعجزٍ وهميٍّ في الخانة الثالثة
 * عشرة. وهي القاعدةُ نفسُها المعمول بها في إقفال الوردية في هذا المشروع.
 *
 * ── ولا يكتب هذا الصنفُ شيئاً ───────────────────────────────────────────
 *
 * ⚠ قراءةٌ خالصة: لا `INSERT` ولا `UPDATE` ولا قيد. ولا يغيّر معادلةً قائمة —
 * يحسب بما تحسب به المنظومةُ نفسُها، ويقرأ بما تقرأ به دالّتُها، ثمّ يقول
 * «نعم» أو «لا».
 */
class ExternalPricingGuard
{
    /**
     * نصُّ الاعتذار — **بكلمات المالك حرفاً بحرف** (11 سبتمبر 2026).
     *
     * ⚠ ولا يُشرح للمستخدم أيُّ سعرٍ اختلّ ولا بكم: الوكيلُ واقفٌ أمام زبون،
     * ورقمٌ داخليٌّ في وجهه يجعله يساوم عليه. والسببُ يُقال لمن يُصلحه — في
     * سجلّ الخادم — لا لمن لا يملك إصلاحه.
     */
    public const REFUSAL = 'نأسف لعدم اتمام التحويل . الاسعار في طور التحديث عليك مراجعة الشركة';

    /**
     * هامشُ تسامحٍ لحساب الفاصلة العائمة — انظر ترويسة الصنف.
     *
     * ⚠ ثلاثةُ أعشارِ الألف من وحدة العملة: أصغرُ من أن يخفي خسارةً حقيقية
     * (أصغرُ خسارةٍ مقيسةٍ في الصفوف المعطوبة كانت 5.000)، وأكبرُ بعشرة
     * مليارات من ضجيج الضرب العائم.
     */
    public const EPSILON = 0.0005;

    /**
     * سعرُ البيع المعتمد لخدمةٍ في وجهة — **القراءةُ الوحيدة في المنظومة**.
     *
     * ⚠ هذا الاستعلامُ هو استعلامُ `dbo.SalePrice_mo_Value` حرفاً بحرف، وهي
     * الدالّةُ التي تحسب ما يستلمه المستفيد. فمن قرأ بغيره قرأ رقماً آخر —
     * وهو بعينه ما أوقع العطب.
     *
     * وشرطاه اللذان لا يسقط أحدُهما:
     *
     *   `AppBriceTB` — تقرّر **أيَّ قائمةِ أسعارِ فرعٍ** يستعملها التطبيق.
     *     وبدونها يُقرأ سعرُ فرعٍ آخر: الجنيه السوداني وحدَه له ستُّ قيمٍ
     *     بحسب الفرع (338.983 · 370.370 · 425.531 · 555.555 · 606.060 · 653.594).
     *
     *   `b.BankID = ?` — **الخدمة**. مصر: 5.550 للبريد وفودافون والتسليم
     *     باليد، و5.300 للبنكية وإنستا باي. وإسقاطُه يجعل خمسةَ صفوفٍ تتأهّل.
     *
     * @return float|null  لا شيءَ إذا لم يُسعَّر هذا الاقتران بعد.
     */
    public function prices(int $countryId, int $serviceId): array
    {
        return DB::select("
            SELECT ISNULL(a.SalePrice, 1) AS SalePrice
            FROM NewCurrencyPriceOwnDetailsTb AS a
            INNER JOIN NewCurrencyPricesOwnTb AS b ON a.CPID = b.ID
            INNER JOIN CountiresTb AS c ON b.CountryID = c.ID
                                       AND a.CurrencyIDTo = c.DefualtCurrency
            INNER JOIN AppBriceTB AS e ON b.CountryID   = e.CountryID
                                      AND b.AccountType = e.AccountType
                                      AND b.BranchID    = e.BranchID
            WHERE a.CurrencyIDFrom = 1
              AND b.PriceType = 2
              AND b.CountryID = ?
              AND b.BankID    = ?
        ", [$countryId, $serviceId]);
    }

    /**
     * السعرُ حين يكون **واحداً لا غير** — وإلّا فلا سعر.
     *
     * ⚠⚠ **ولماذا يُرفض التعدّد بدل أن يُؤخذ أوّلُه؟**
     *
     * لأنّ التعدّدَ هو بعينه العطبُ الذي كشفه المالك، مرفوعاً درجةً واحدة.
     * `SELECT @SalePrice = …` في المحفّز وفي `SalePrice_mo_Value` **لا تختار**
     * حين تتعدّد الصفوف: تُبقي آخرَ صفٍّ يصله المنفّذ، وهو ترتيبُ خطّةٍ لا
     * قاعدةُ عمل. فلو صار لاقترانٍ صفّان، لكان السعرُ المنفَّذ رقماً لا يعرفه
     * أحدٌ سلفاً — ولا يُعرض على وكيلٍ رقمٌ لا نضمن أنه سيُنفَّذ.
     *
     * ⚠ وهذا ليس احتياطاً نظرياً: العطبُ الأصليّ كان خمسةَ صفوفٍ لمصر، وكلَّفَ
     * تسعَ حوالاتٍ بهامشٍ سالب. الفرقُ أنّ ذاك كان تعدّداً في الخدمات وهذا
     * تعدّدٌ في الخدمة الواحدة.
     *
     * ⚠ والقاعدةُ اليوم نظيفة (تسعةُ اقتراناتٍ، صفٌّ لكلٍّ منها)، فهذا الشرطُ
     * لا يكلّف شيئاً الآن ويمنع إدخالاً مكرَّراً غداً من أن يصير سعراً عشوائياً.
     */
    public function rate(int $countryId, int $serviceId): ?float
    {
        return $this->register($countryId, $serviceId)['rate'];
    }

    /*
     * ══════════════════════════════════════════════════════════════════════
     *  ⚠⚠ «المسجَّلُ خطأً في حكم غير المسجَّل» — أمرُ المالك 11 سبتمبر 2026
     * ══════════════════════════════════════════════════════════════════════
     *
     * «أيُّ عملةٍ بدون سعرٍ امنع ظهورَها في الشاشة، ولا تسمح بظهور إلّا
     *  العملات المسجّلة بذكاء: إذا عملةٌ مسجّلةٌ خطأً وتسبّب خسائر فاجعلها في
     *  حكم غير المسجَّلة، ولا تظهر للعميل في الشاشة ولا في تنفيذ الحوالة
     *  الخارجية. والسعرُ الظاهر في الحوالة الخارجية يجب أن يكون ظاهراً في
     *  شاشة الأسعار».
     *
     * ── قرارٌ واحدٌ يحكم ثلاثةَ أبواب ───────────────────────────────────
     *
     * [register] هي **المرجعُ الوحيد** لسؤال «هل هذا الاقتران صالح؟»، وتناديها
     * ثلاثةُ أبوابٍ لا اثنان:
     *
     *   ١) لوحةُ الأسعار    — فلا يُعرض ما لا يُنفَّذ
     *   ٢) قائمةُ الخدمات   — فلا يُختار ما لن يُقبل
     *   ٣) التسعيرُ والإنشاء — فلا يُنفَّذ ما ليس على اللوحة
     *
     * وثلاثةُ أبوابٍ بثلاثة أحكامٍ تفترق عند أوّل تعديل، ثمّ يرى الوكيلُ خدمةً
     * في القائمة تختفي من اللوحة وتُردّ عند الإرسال — وهو «الإحراجُ مع الزبائن»
     * الذي نصَّ الأمرُ على منعه.
     *
     * ── وثلاثةُ أسبابٍ تجعل الاقترانَ «غيرَ مسجَّل» ─────────────────────
     *
     * ⚠ **حكمٌ بنيويٌّ لا عيّنات.** يُقرأ ما يقرؤه المحرّكُ نفسُه ويُحكم عليه،
     * ولا يُستنتج من تجريب مبالغ: عيّناتٌ تمرّ قد يفلت منها مبلغٌ لم يُجرَّب،
     * وقراءةُ المدخلات لا يفلت منها شيء.
     *
     *   NO_PRICE        لا صفَّ سعرٍ أصلاً.
     *
     *   AMBIGUOUS_PRICE أكثرُ من صفّ. و`SELECT @var =` لا تختار حين تتعدّد
     *                   الصفوف: تُبقي آخرَ ما يصله المنفّذ. فالسعرُ المنفَّذ
     *                   رقمٌ لا يعرفه أحدٌ سلفاً — ولا يُعرض ما لا نضمنه.
     *                   وهو بعينه العطبُ الأصليّ مرفوعاً درجة.
     *
     *   BAD_PRICE       سعرٌ صفرٌ أو سالب. ⚠ وهذا **يعبر فحصَ الهامش سليماً**:
     *                   بسعر صفرٍ يكون المسلَّم صفراً والصافي صفراً والهامشُ
     *                   صفراً — فيمرّ الفحصُ الحسابيّ بينما المستفيد يستلم
     *                   لا شيء. فحصُ الهامش وحدَه لا يمسك هذه.
     *
     *   BAD_DISCOUNT    حسمٌ سالبٌ في `CATEGORYTYPESDETAILSTB`. وهو بالضبط
     *                   «مسجَّلةٌ خطأً وتسبّب خسائر»: بالسعر الموحَّد يصير
     *                   الهامشُ هو الحسم، فحسمٌ سالبٌ = خسارةٌ في كلّ حوالةٍ
     *                   تقع في تلك الشريحة.
     */
    public function register(int $countryId, int $serviceId): array
    {
        $key = "$countryId:$serviceId";
        if (isset($this->memo[$key])) {
            return $this->memo[$key];
        }

        $rows = $this->prices($countryId, $serviceId);

        $verdict = match (true) {
            count($rows) === 0 => ['rate' => null, 'reason' => 'NO_PRICE'],
            count($rows) > 1   => ['rate' => null, 'reason' => 'AMBIGUOUS_PRICE'],
            (float) $rows[0]->SalePrice <= 0
                               => ['rate' => null, 'reason' => 'BAD_PRICE'],
            $this->hasNegativeDiscount($serviceId)
                               => ['rate' => null, 'reason' => 'BAD_DISCOUNT'],
            default            => ['rate' => (float) $rows[0]->SalePrice, 'reason' => null],
        };

        return $this->memo[$key] = $verdict;
    }

    /** هل الاقترانُ صالحٌ للعرض وللتنفيذ معاً؟ */
    public function isAvailable(int $countryId, int $serviceId): bool
    {
        return $this->register($countryId, $serviceId)['rate'] !== null;
    }

    /**
     * حسمٌ سالبٌ في أيّ شريحةٍ من شرائح هذه الخدمة.
     *
     * ⚠ `SalePrice_mo_Value` تطرح الحسمَ من قيمة الحوالة، فالحسمُ السالب
     * **يزيدها** — أي يُسلَّم للمستفيد أكثرُ ممّا قُبض مقوَّماً، وهي الخسارة
     * بعينها. ويقع مهما كان السعرُ صحيحاً، فلا يمسكه فحصُ السعر.
     */
    private function hasNegativeDiscount(int $serviceId): bool
    {
        $row = DB::selectOne(
            'SELECT COUNT(*) AS n FROM CATEGORYTYPESDETAILSTB WHERE CATID = ? AND DisVal < 0',
            [$serviceId]
        );

        return ((int) ($row->n ?? 0)) > 0;
    }

    /** ذاكرةُ الطلب الواحد — اللوحةُ تسأل عن كلّ اقترانٍ مرّاتٍ لا مرّة. */
    private array $memo = [];

    /**
     * ما يستلمه المستفيد — **من دالّة المنظومة، لا من حسابٍ موازٍ**.
     *
     * ⚠ `SalePrice_mo_Value` تطبّق جدولَ الحسم بشرائحه وحدودِه القصوى
     * (`CATEGORYTYPESDETAILSTB` و`ExtTraServiceTypeTb.MaxValue`)، ومحاكاتُها
     * في PHP تعني معادلةً ثانيةً تفترق عنها عند أوّل تعديلٍ في المكتب
     * الخلفيّ — ثمّ يُمنع وكيلٌ لخسارةٍ لا وجودَ لها، أو تمرّ خسارةٌ حقيقية.
     */
    public function net(int $countryId, float $amount, int $serviceId, int $isPrivate): float
    {
        /*
         * ⚠⚠ **الصبُّ الصريح `DECIMAL(18,3)` ليس تجميلاً — بدونه ينهار النداء.**
         *
         * توقيعُ الدالّة `@value as int`. والسائقُ يربط عدد PHP العشريَّ
         * **نصّاً**، فيصل SQL Server السلسلةُ '60.4' ويحاول تحويلها إلى `int`
         * مباشرةً فيرمي:
         *
         *   SQLSTATE[22018] Conversion failed when converting the nvarchar
         *   value '60.4' to data type int
         *
         * أي أنّ **كلَّ مبلغٍ كسريّ** — و60.50 د.ل مبلغٌ عاديّ عند الشبّاك —
         * كان يُسقط التسعيرة بخطأ 500. وهو عطبٌ قائمٌ من قبلُ في
         * `externalQuote` لا شيءٌ استُحدث هنا.
         *
         * ⚠ والصبُّ إلى `DECIMAL` **يطابق المحفّز حرفاً بحرف**: هو يمرّر
         * `A.[CurrRecievedVal]` وهو عمودٌ عشريّ، فيحوّله SQL Server إلى `int`
         * تحويلاً رقمياً (بالتقريب) لا نصّياً. فلو صببتُ إلى `INT` في PHP
         * لاختلف التقريبُ عن تقريب المحرّك — وعدنا إلى «معروضٌ يخالف المنفَّذ»
         * من بابٍ آخر.
         */
        $row = DB::selectOne(
            'SELECT ISNULL(dbo.SalePrice_mo_Value(?, CAST(? AS DECIMAL(18,3)), ?, ?), 0) AS NetTotal',
            [$countryId, $amount, $serviceId, $isPrivate]
        );

        return (float) ($row->NetTotal ?? 0);
    }

    /**
     * الحكمُ على حوالةٍ قبل تنفيذها.
     *
     * ⚠ يُنادى **قبل الإدراج**، لا بعده: بعد الإدراج يكون القيدُ قد كُتب،
     * والتراجعُ عنه حركةٌ ماليةٌ ثانيةٌ في الدفتر. والمنعُ قبل الباب لا يترك
     * أثراً أصلاً.
     *
     * @return array{ok:bool, reason:?string, rate:?float, delivered:float,
     *               net:float, margin:float}
     */
    public function evaluate(int $countryId, int $serviceId, float $amount, int $isPrivate = 0): array
    {
        $reg  = $this->register($countryId, $serviceId);
        $rate = $reg['rate'];

        /*
         * ⚠ **خدمةٌ بلا سعرٍ تُمنع، ولا يُستعار لها سعرُ خدمةٍ أخرى.**
         *
         * وهي بعينها حالةُ «الأسعار في طور التحديث» التي وصفها الأمر: اقترانٌ
         * لم يُسعَّر بعد في المكتب الخلفيّ. والمعلومُ اليوم: «بنكك» في السودان.
         *
         * ⚠ ولو مرّت، لكتب المحفّزُ `TransPrice` **فارغةً** بعد إضافة شرط
         * الخدمة إليه — حوالةٌ بلا سعرٍ في الدفتر، وهي أسوأُ من رفضٍ مؤدّب.
         */
        if ($rate === null) {
            return [
                'ok'        => false,
                'reason'    => $reg['reason'],
                'rate'      => null,
                'delivered' => 0.0,
                'net'       => 0.0,
                'margin'    => 0.0,
            ];
        }

        $delivered = $amount * $rate;
        $net       = $this->net($countryId, $amount, $serviceId, $isPrivate);
        $margin    = $delivered - $net;

        /*
         * ⚠ والصفرُ يمرّ. الأمرُ نصّ على منع **السالب** وحدَه، وعلى أنّ ما كان
         * «في صالح الشركة والربح +» يُنفَّذ. والصفرُ ليس خسارة: هو خدمةٌ
         * سعّرها المكتبُ الخلفيّ بلا حسم، وأكثرُ الخدمات اليوم كذلك — فمنعُه
         * كان سيوقف العملَ كلَّه في يوم النشر.
         */
        $ok = $margin >= -self::EPSILON;

        return [
            'ok'        => $ok,
            'reason'    => $ok ? null : 'NEGATIVE_MARGIN',
            'rate'      => $rate,
            'delivered' => $delivered,
            'net'       => $net,
            'margin'    => $margin,
        ];
    }
